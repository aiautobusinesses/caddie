#!/usr/bin/env node
/**
 * scripts/generate-functions-sql.mjs
 *
 * Regenerates supabase/functions.sql from the migration files.
 *
 * Strategy: walk every supabase/migrations/*.sql file in filename order,
 * extract all CREATE OR REPLACE FUNCTION blocks, keep only the last
 * definition seen for each function name (later migrations win), then
 * write them out in the order they were last defined.
 *
 * Usage:
 *   node scripts/generate-functions-sql.mjs
 */

import { readFileSync, readdirSync, writeFileSync } from "fs"
import { join, dirname } from "path"
import { fileURLToPath } from "url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const migrationsDir = join(root, "supabase", "migrations")
const outputFile = join(root, "supabase", "functions.sql")

const migrationFiles = readdirSync(migrationsDir)
  .filter((f) => f.endsWith(".sql"))
  .sort()

/**
 * Extract every CREATE OR REPLACE FUNCTION block from a SQL string.
 * Blocks are delimited by `$$;` (the end of a plpgsql body).
 * Returns an array of { name, block } objects.
 */
function extractFunctions(sql) {
  const results = []
  // Match from CREATE OR REPLACE FUNCTION up to and including the closing $$;
  const re = /create\s+or\s+replace\s+function\s+(?:\w+\.)?(\w+)\s*\([^]*?\$\$;/gi
  let m
  while ((m = re.exec(sql)) !== null) {
    results.push({ name: m[1].toLowerCase(), block: m[0].trimEnd() })
  }
  return results
}

// Map from function name → { block, migration } — later migrations overwrite earlier ones.
const seen = new Map()

for (const file of migrationFiles) {
  const sql = readFileSync(join(migrationsDir, file), "utf8")
  for (const { name, block } of extractFunctions(sql)) {
    seen.set(name, { block, migration: file })
  }
}

if (seen.size === 0) {
  console.error("No functions found in migrations — check migration file format.")
  process.exit(1)
}

const header = `-- supabase/functions.sql
--
-- Generated by scripts/generate-functions-sql.mjs — do not edit by hand.
-- Run \`node scripts/generate-functions-sql.mjs\` to regenerate.
--
-- Source: supabase/migrations/*.sql (last definition of each function wins)

`

const body = [...seen.values()]
  .map(({ block, migration }) => `-- last changed: ${migration}\n${block}`)
  .join("\n\n")

writeFileSync(outputFile, header + body + "\n")
console.log(`Wrote ${seen.size} function(s) to supabase/functions.sql`)
